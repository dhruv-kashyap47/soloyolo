import { createHash } from 'node:crypto';
import allowlist from '../../config/third-party.json';
import {
  buildCsp,
  inlineScriptHashes,
  inlineStyleHashes,
  normalizeOrigins,
  PAGES_DEV_NOINDEX_PATTERNS,
  renderHeaders,
  SECURITY_HEADERS,
} from '../../scripts/lib/csp.mjs';
import { checkHeaders } from '../../scripts/lib/headers.mjs';
import { describe, expect, it } from 'vitest';

const sha = (text: string) =>
  `'sha256-${createHash('sha256').update(text, 'utf8').digest('base64')}'`;

describe('CSP inline-script hashing (P7-03)', () => {
  it('hashes executable inline scripts and ignores JSON-LD and external files', () => {
    const html = [
      '<script>const a = 1;</script>',
      '<script type="module">export const b = 2;</script>',
      '<script type="application/ld+json">{"@type":"Thing"}</script>',
      '<script src="/_astro/page.js"></script>',
      '<script type="text/javascript">const c = 3;</script>',
    ].join('');

    expect(inlineScriptHashes(html)).toEqual(
      [sha('const a = 1;'), sha('export const b = 2;'), sha('const c = 3;')].sort(),
    );
  });

  it('de-duplicates the same script repeated on every page', () => {
    const html = '<script>same()</script><script>same()</script>';
    expect(inlineScriptHashes(html)).toEqual([sha('same()')]);
  });

  it('returns no hashes for a page with only external scripts', () => {
    expect(inlineScriptHashes('<script src="/_astro/page.js"></script>')).toEqual([]);
  });

  it('hashes inline style elements separately from scripts', () => {
    const html =
      '<style>astro-island{display:contents}</style><style media="print">.x{display:none}</style>';
    expect(inlineStyleHashes(html)).toEqual([
      sha('astro-island{display:contents}'),
      sha('.x{display:none}'),
    ]);
    expect(inlineScriptHashes(html)).toEqual([]);
  });
});

describe('third-party allowlist (P7-14)', () => {
  it('accepts only bare https origins and de-duplicates them', () => {
    expect(
      normalizeOrigins([
        'https://pagead2.googlesyndication.com',
        'https://pagead2.googlesyndication.com/',
        'https://fundingchoicesmessages.google.com',
      ]),
    ).toEqual([
      'https://fundingchoicesmessages.google.com',
      'https://pagead2.googlesyndication.com',
    ]);
  });

  it('rejects plain http, paths and empty entries', () => {
    expect(() => normalizeOrigins(['http://example.com'])).toThrow(/https/);
    expect(() => normalizeOrigins(['https://example.com/ads.js'])).toThrow(/bare origin/);
    expect(() => normalizeOrigins(['https://example.com/?x=1'])).toThrow(/bare origin/);
  });

  it('fails closed while the capture is empty', () => {
    expect(allowlist.cmp).toEqual([]);
    expect(allowlist.adStack).toEqual([]);
    expect(allowlist.capturedOn).toBeNull();
  });
});

describe('Content-Security-Policy and Pages headers (P7-03)', () => {
  const csp = buildCsp({
    scriptHashes: [sha('const a = 1;')],
    origins: ['https://pagead2.googlesyndication.com'],
  });

  it('keeps script execution on self plus hashes, with no unsafe-inline', () => {
    expect(csp).toContain(`script-src 'self' ${sha('const a = 1;')}`);
    expect(csp).not.toMatch(/script-src[^;]*'unsafe-inline'/);
  });

  it('keeps styles on self plus captured origins, with no unsafe-inline', () => {
    expect(csp).toContain("style-src 'self' https://pagead2.googlesyndication.com");
    expect(csp).not.toMatch(/style-src[^;]*'unsafe-inline'/);
  });

  it('allows an inline style element by hash', () => {
    const styleCsp = buildCsp({ styleHashes: [sha('astro-island{display:contents}')] });
    expect(styleCsp).toContain(`style-src 'self' ${sha('astro-island{display:contents}')}`);
  });

  it('pins the captured origins into every network directive', () => {
    expect(csp).toContain("connect-src 'self' https://pagead2.googlesyndication.com");
    expect(csp).toContain('frame-src https://pagead2.googlesyndication.com');
    expect(csp).toContain("img-src 'self' data: https://pagead2.googlesyndication.com");
  });

  it('blocks framing, objects, forms and workers', () => {
    expect(csp).toContain("frame-ancestors 'none'");
    expect(csp).toContain("object-src 'none'");
    expect(csp).toContain("form-action 'self'");
    expect(csp).toContain("worker-src 'none'");
  });

  it('falls back to frame-src none with an empty allowlist', () => {
    expect(buildCsp()).toContain("frame-src 'none'");
  });

  it('renders the static security headers and immutable asset caching', () => {
    const file = renderHeaders({ csp });

    for (const [name, value] of SECURITY_HEADERS) {
      expect(file).toContain(`${name}: ${value}`);
    }
    expect(file).toContain(`Content-Security-Policy: ${csp}`);
    expect(file).toContain('/_astro/*');
    expect(file).toContain('Cache-Control: public, max-age=31536000, immutable');
    expect(file).toContain('/fonts/*');
    expect(file.startsWith('# Generated by scripts/build-headers.mjs')).toBe(true);
  });
});

describe('CSP reporting', () => {
  it('omits report directives and the endpoint header when unset', () => {
    const csp = buildCsp();
    const file = renderHeaders({ csp });

    expect(csp).not.toContain('report-uri');
    expect(csp).not.toContain('report-to');
    expect(file).not.toContain('Reporting-Endpoints');
  });

  it('adds report-uri, report-to and Reporting-Endpoints when configured', () => {
    const reportUrl = 'https://reports.example.com/csp';
    const csp = buildCsp({ reportUrl });
    const file = renderHeaders({ csp, reportUrl });

    expect(csp).toContain(`report-uri ${reportUrl}`);
    expect(csp).toContain('report-to csp');
    expect(file).toContain(`Reporting-Endpoints: csp="${reportUrl}"`);
  });

  it('rejects a non-http URL or one with embedded credentials', () => {
    expect(() => buildCsp({ reportUrl: 'javascript:alert(1)' })).toThrow(/http/);
    expect(() => buildCsp({ reportUrl: 'https://user:pass@example.com/csp' })).toThrow(
      /credentials/,
    );
  });
});

describe('approved Google tag policy', () => {
  const analytics = {
    script: ['https://www.googletagmanager.com'],
    connect: [
      'https://www.googletagmanager.com',
      'https://www.google-analytics.com',
      'https://*.google-analytics.com',
    ],
    img: ['https://www.google-analytics.com'],
    frame: [],
  };

  it('allows the container script and GA4 collect hosts in the right directives', () => {
    const csp = buildCsp({ analytics });

    expect(csp).toContain("script-src 'self' https://www.googletagmanager.com");
    expect(csp).toMatch(/connect-src[^;]*https:\/\/www\.googletagmanager\.com/);
    expect(csp).toMatch(/connect-src[^;]*https:\/\/www\.google-analytics\.com/);
    expect(csp).toMatch(/connect-src[^;]*https:\/\/\*\.google-analytics\.com/);
    expect(csp).not.toContain("script-src 'self' https://www.google-analytics.com");
    expect(csp).toContain("frame-src 'none'");
  });

  it('indexes the production hosts and keeps every pages.dev alias noindex', () => {
    const file = renderHeaders({
      csp: buildCsp({ analytics }),
      siteUrl: 'https://soloyolotools.com',
    });

    expect(file).toContain('https://soloyolotools.com/*');
    expect(file).toContain('https://www.soloyolotools.com/*');
    expect(file).toContain('  ! X-Robots-Tag\n  X-Robots-Tag: index, follow');
    for (const pattern of PAGES_DEV_NOINDEX_PATTERNS) {
      expect(file).toContain(`${pattern}\n  X-Robots-Tag: noindex`);
    }
    expect(checkHeaders({ headers: file, siteUrl: 'https://soloyolotools.com' })).toEqual([]);
  });

  it('never asserts index, follow when the site URL is a pages.dev host', () => {
    for (const siteUrl of ['https://soloyolo.pages.dev', 'https://main.soloyolo.pages.dev']) {
      const file = renderHeaders({ csp: buildCsp(), siteUrl });

      expect(file).not.toContain('index, follow');
      expect(checkHeaders({ headers: file, siteUrl })).toEqual([]);
    }
  });

  it('rejects a preview artifact that still claims index, follow', () => {
    const file = [
      renderHeaders({ csp: buildCsp(), siteUrl: 'https://soloyolo.pages.dev' }),
      'https://:project.pages.dev/*',
      '  X-Robots-Tag: index, follow',
    ].join('\n');

    expect(checkHeaders({ headers: file, siteUrl: 'https://soloyolo.pages.dev' })).toContain(
      '_headers: a preview build for soloyolo.pages.dev must not assert index, follow',
    );
  });

  it('reports a missing pages.dev noindex rule', () => {
    const file = renderHeaders({ csp: buildCsp(), siteUrl: 'https://soloyolotools.com' }).replace(
      /\nhttps:\/\/:(?:project|version\.:project)\.pages\.dev\/\*\n {2}X-Robots-Tag: noindex/g,
      '',
    );

    expect(checkHeaders({ headers: file, siteUrl: 'https://soloyolotools.com' })).toContain(
      `_headers: missing the *.pages.dev noindex rule ${PAGES_DEV_NOINDEX_PATTERNS[0]}`,
    );
  });
});
